const plural = (n, one, many) => `${n} ${Number(n) === 1 ? one : many}`;
const ord = (n) => {
  const v = Number(n);
  const s = v % 100 >= 11 && v % 100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' }[v % 10] || 'th');
  return `${n}${s}`;
};

